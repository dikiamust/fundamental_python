# int
print('Int')
a = int(1)
print(a)  # 1

b = int(2.8)
print(b)  # 2

c = int("3")
print(c)  # 3


# float
print('\nFloat')
d = float(1)
print(d)  # 1.0

e = float(2.8)
print(e)  # 2.8

f = float("3")
print(f)  # 3.0

g = float("4.2")
print(g)  # 4.2


# string
print('\nString')
h = str("s1")
print(h)  # s1

i = str(2)
print(i)  # 2

j = str(3.0)
print(j)  # 3.0