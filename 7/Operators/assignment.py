# Assignment Operators

# =
print('\nAssignment (=)')
x = 5
print(x)  # 5

# +=
print('\nAddition Assignment (+=)')
x = 5
x += 3
print(x)  # 8

# -=
print('\nSubtraction Assignment (-=)')
x = 5
x -= 3
print(x)  # 2

# *=
print('\nMultiplication Assignment (*=)')
x = 5
x *= 3
print(x)  # 15

# /=
print('\nDivision Assignment (/=)')
x = 6
x /= 3
print(x)  # 2.0

# %=
print('\nModulus Assignment (%=)')
x = 5
x %= 3
print(x)  # 2

# //=
print('\nFloor Division Assignment (//=)')
x = 7
x //= 3
print(x)  # 2

# **=
print('\nExponentiation Assignment (**=)')
x = 2
x **= 3
print(x)  # 8

# &=
print('\nBitwise AND Assignment (&=)')
x = 5
x &= 3
print(x)  # 1

# |=
print('\nBitwise OR Assignment (|=)')
x = 5
x |= 3
print(x)  # 7

# ^=
print('\nBitwise XOR Assignment (^=)')
x = 5
x ^= 3
print(x)  # 6

# >>=
print('\nRight Shift Assignment (>>=)')
x = 8
x >>= 3
print(x)  # 1

# <<=
print('\nLeft Shift Assignment (<<=)')
x = 5
x <<= 3
print(x)  # 40

# :=
print('\nWalrus Operator (:=)')
print(x := 3)  # 3
print(x)       # 3