# Access List Items

# Access Item
print('\nAccess Item')
a = ["apple", "banana", "cherry"]
print(a[1])  # banana

# Range of Indexes
print('\nRange of Indexes')
b = ["apple", "banana", "cherry", "orange", "kiwi", "melon", "mango"]
print(b[2:5])  # ['cherry', 'orange', 'kiwi']

# Range from the Beginning
print('\nRange from the Beginning')
c = ["apple", "banana", "cherry", "orange", "kiwi", "melon", "mango"]
print(c[:4])  # ['apple', 'banana', 'cherry', 'orange']

# Range to the End
print('\nRange to the End')
d = ["apple", "banana", "cherry", "orange", "kiwi", "melon", "mango"]
print(d[2:])  # ['cherry', 'orange', 'kiwi', 'melon', 'mango']